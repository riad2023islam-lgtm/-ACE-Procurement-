"""Django settings for the ACE Procurement Intelligence project (SE331).

No secrets are hardcoded: SECRET_KEY comes from the DJANGO_SECRET_KEY
environment variable, or is generated once and stored in a git-ignored file.
"""
import os
from pathlib import Path

from django.core.management.utils import get_random_secret_key

BASE_DIR = Path(__file__).resolve().parent.parent


def _load_secret_key() -> str:
    from_env = os.environ.get("DJANGO_SECRET_KEY")
    if from_env:
        return from_env
    key_file = BASE_DIR / ".secret_key"          # listed in .gitignore
    if key_file.exists():
        return key_file.read_text().strip()
    key = get_random_secret_key()
    key_file.write_text(key)
    return key


